// Welle V1.9.113 "Online-Teilnahme an Veranstaltungen" -- see network.lapis.cloud.server.events.EventConferenceProvisioner,
// network.lapis.cloud.server.events.EventOnlineAccess and docs/features/event-online-participation.adoc (V93__event_online_participation.sql).
//
// **One new table.** `event_conference` is the server-side bookkeeping of the Lapis video conference an event creates on its FIRST online
// join (event.online_kind = LAPIS_CONFERENCE). At most one row per event (the event id is the primary key); the `conference_room` it points
// to (`conference_room_id`, UNIQUE) is an ordinary conference room that the whole conference RPC surface treats as off limits
// (EventConferenceGuard) -- the token is only ever minted by `IEventService.joinEventOnline`.
//
// **Why claim_token / claimed_at / status.** The first join must create the LiveKit room exactly once even under concurrent first joins,
// and LiveKit must never be called inside a database transaction. The winner of the PENDING insert (or of the conditional take-over of a
// FAILED / orphaned PENDING row) is the only one allowed to write ACTIVE/FAILED -- it proves that with `claim_token` (fencing). A PENDING
// row older than `pendingTakeoverAfter` (claimed_at) was abandoned by a crashed claimer and may be taken over.
//
// **Time fields.** `window_opens_at`/`window_closes_at` are UTC-based timestamps (class A, derived from the event's wall-clock start/end
// through OrganizationTimeZone) -- never compare them with `event.starts_at`/`ends_at` (class B) directly.
//
// Cross-field CHECK constraints (ACTIVE implies a conference room, window ordering, the status enum) are SQL-only.
import dev.kuml.profile.erm.ermMappingProfile
import dev.kuml.uml.Multiplicity
import dev.kuml.uml.dsl.applyProfile
import dev.kuml.uml.dsl.stereotype

classDiagram(name = "EventOnline") {
    applyProfile(ermMappingProfile)

    // 39-events.kuml.kts-owned stub -- id-only.
    val event = classOf(name = "Event") {
        stereotype("Entity") { "tableName" to "event"; "kotlinObjectName" to "EventTable" }
        attribute(name = "id", type = "UUID") {
            stereotype("Id")
            stereotype("Column") { "columnName" to "id" }
        }
    }

    // 27-conference.kuml.kts-owned stub -- id-only.
    val conferenceRoom = classOf(name = "ConferenceRoom") {
        stereotype("Entity") { "tableName" to "conference_room"; "kotlinObjectName" to "ConferenceRoomTable" }
        attribute(name = "id", type = "UUID") {
            stereotype("Id")
            stereotype("Column") { "columnName" to "id" }
        }
    }

    val eventConference = classOf(name = "EventConference") {
        stereotype("Entity") { "tableName" to "event_conference"; "kotlinObjectName" to "EventConferenceTable" }
        stereotype("Index") { "columns" to listOf("status", "window_closes_at"); "name" to "idx_event_conference_status_closes" }
        stereotype("Index") { "columns" to listOf("conference_room_id"); "name" to "uq_event_conference_room"; "unique" to true }

        attribute(name = "eventId", type = "UUID") {
            stereotype("Id")
            stereotype("Column") { "columnName" to "event_id"; "fkEntity" to "Event" }
        }
        // NULL until the conference room exists (status ACTIVE).
        attribute(name = "conferenceRoomId", type = "UUID") {
            multiplicity = Multiplicity(0, 1)
            stereotype("Column") { "columnName" to "conference_room_id"; "fkEntity" to "ConferenceRoom" }
        }
        // "lc-<uuid>", generated by the claimer.
        attribute(name = "livekitRoomName", type = "String") {
            multiplicity = Multiplicity(0, 1)
            stereotype("Column") { "columnName" to "livekit_room_name"; "sqlType" to "VARCHAR(64)" }
        }
        // PENDING | ACTIVE | ENDED | FAILED
        attribute(name = "status", type = "String") {
            stereotype("Column") { "columnName" to "status"; "sqlType" to "VARCHAR(16)" }
        }
        // Fencing token: only the current claimer may write ACTIVE/FAILED.
        attribute(name = "claimToken", type = "UUID") {
            stereotype("Column") { "columnName" to "claim_token" }
        }
        attribute(name = "claimedAt", type = "LocalDateTime") {
            stereotype("Column") { "columnName" to "claimed_at" }
        }
        attribute(name = "windowOpensAt", type = "LocalDateTime") {
            stereotype("Column") { "columnName" to "window_opens_at" }
        }
        attribute(name = "windowClosesAt", type = "LocalDateTime") {
            stereotype("Column") { "columnName" to "window_closes_at" }
        }
        attribute(name = "createdAt", type = "LocalDateTime") {
            stereotype("Column") { "columnName" to "created_at" }
        }
        attribute(name = "endedAt", type = "LocalDateTime") {
            multiplicity = Multiplicity(0, 1)
            stereotype("Column") { "columnName" to "ended_at" }
        }
    }
}
