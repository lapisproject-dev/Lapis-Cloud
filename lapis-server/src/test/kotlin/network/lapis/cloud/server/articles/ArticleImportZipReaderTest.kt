package network.lapis.cloud.server.articles

import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.collections.shouldContainExactly
import io.kotest.matchers.shouldBe
import kotlin.random.Random

/**
 * Welle V1.9.106 -- [ArticleImportZipReader] against valid and hostile ZIPs. Every archive is built at runtime ([TestZipBuilder]); malformed
 * shapes are assembled byte by byte. No test touches the file system.
 */
class ArticleImportZipReaderTest :
    FunSpec({
        val jpegish = "payload".toByteArray()

        fun rejected(zip: ByteArray): ZipRejectReason? = (ArticleImportZipReader.read(zip) as? ZipReadResult.Rejected)?.reason

        fun ok(zip: ByteArray) = ArticleImportZipReader.read(zip) as ZipReadResult.Ok

        test("a plain ZIP of images is read: slug, file name and bytes; deflated and stored entries both work") {
            val result =
                ok(
                    TestZipBuilder.build(
                        entries =
                            listOf(
                                TestZipEntry(name = "mein-artikel.jpg", data = jpegish),
                                TestZipEntry(name = "zweiter_artikel.PNG", data = jpegish + 1, method = 0),
                                TestZipEntry(name = "dritter.jpeg", data = Random(3).nextBytes(2000)),
                            ),
                    ),
                )
            result.images.map { it.slug } shouldContainExactly listOf("mein-artikel", "zweiter_artikel", "dritter")
            result.images.map { it.fileName } shouldContainExactly listOf("mein-artikel.jpg", "zweiter_artikel.PNG", "dritter.jpeg")
            result.images[0].bytes.toList() shouldBe jpegish.toList()
            result.images[2].bytes.size shouldBe 2000
            result.duplicateSlugs shouldBe emptySet()
            result.ignoredSystemFiles shouldBe 0
        }

        test("a ZIP written by scripts/prepare-article-images.py (Python zipfile, ZIP_STORED, Unix attributes 0644) is accepted") {
            // generated by the helper script's own writer settings; two entries, mein-artikel.jpg and zwei_teile.png
            val fromPython =
                java.util.Base64.getDecoder().decode(
                    "UEsDBBQAAAAAAAAAIQBDJQhNCgAAAAoAAAAQAAAAbWVpbi1hcnRpa2VsLmpwZ0pQRUdEQVRBLTFQSwMEFAAAAAAAAAAhAB6DcAUJAAAACQAAAA4AAAB6d2VpX3RlaWxlLnBuZ1BOR0RBVEEtMlBLAQIUAxQAAAAAAAAAIQBDJQhNCgAAAAoAAAAQAAAAAAAAAAAAAACkAQAAAABtZWluLWFydGlrZWwuanBnUEsBAhQDFAAAAAAAAAAhAB6DcAUJAAAACQAAAA4AAAAAAAAAAAAAAKQBOAAAAHp3ZWlfdGVpbGUucG5nUEsFBgAAAAACAAIAegAAAG0AAAAAAA==",
                )
            val result = ok(fromPython)
            result.images.map { it.fileName } shouldContainExactly listOf("mein-artikel.jpg", "zwei_teile.png")
            String(result.images[0].bytes) shouldBe "JPEGDATA-1"
            String(result.images[1].bytes) shouldBe "PNGDATA-2"
        }

        test("__MACOSX entries (also with non-ASCII names) and .DS_Store are ignored and counted, never inflated") {
            val result =
                ok(
                    TestZipBuilder.build(
                        entries =
                            listOf(
                                TestZipEntry(name = "__MACOSX/", data = ByteArray(0), method = 0, externalAttributes = 0x10L),
                                TestZipEntry(name = "__MACOSX/._äöü.jpg", data = "x".toByteArray()),
                                TestZipEntry(name = ".DS_Store", data = "x".toByteArray()),
                                TestZipEntry(name = "artikel.jpg", data = jpegish),
                            ),
                    ),
                )
            result.images.map { it.slug } shouldBe listOf("artikel")
            result.ignoredSystemFiles shouldBe 3
        }

        test("an empty archive is fine and yields nothing") {
            val result = ok(TestZipBuilder.build(entries = emptyList()))
            result.images shouldBe emptyList()
        }

        test("folders and path tricks reject the whole ZIP as FOLDER_NOT_ALLOWED") {
            for (name in listOf("../a.jpg", "/a.jpg", "a\\b.jpg", "C:a.jpg", "dir/a.jpg", "dir/")) {
                rejected(TestZipBuilder.simple(name to jpegish)) shouldBe ZipRejectReason.FOLDER_NOT_ALLOWED
            }
            // the directory bit of the external attributes, even for a harmless-looking name
            rejected(
                TestZipBuilder.build(
                    entries = listOf(TestZipEntry(name = "ordner", data = ByteArray(0), method = 0, externalAttributes = 0x10L)),
                ),
            ) shouldBe
                ZipRejectReason.FOLDER_NOT_ALLOWED
        }

        test("non-ASCII names, control characters and RTL overrides are BAD_NAME") {
            rejected(TestZipBuilder.simple("ä.jpg" to jpegish)) shouldBe ZipRejectReason.BAD_NAME
            rejected(
                TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a‮gpj.exe".toByteArray(Charsets.UTF_8), data = jpegish))),
            ) shouldBe
                ZipRejectReason.BAD_NAME
            rejected(
                TestZipBuilder.build(
                    entries =
                        listOf(
                            TestZipEntry(name = byteArrayOf('a'.code.toByte(), 0x07, '.'.code.toByte(), 'j'.code.toByte()), data = jpegish),
                        ),
                ),
            ) shouldBe
                ZipRejectReason.BAD_NAME
            rejected(TestZipBuilder.build(entries = listOf(TestZipEntry(name = ByteArray(0), data = jpegish)))) shouldBe
                ZipRejectReason.BAD_NAME
        }

        test("only slug.jpg, slug.jpeg and slug.png are accepted: gif, webp, no extension, uppercase stem, hyphen at the end, too long") {
            for (name in listOf("a.gif", "a.webp", "a", "A.jpg", "a-.jpg", ".jpg", "${"a".repeat(121)}.jpg", "a b.jpg")) {
                rejected(TestZipBuilder.simple(name to jpegish)) shouldBe ZipRejectReason.BAD_NAME
            }
            ok(TestZipBuilder.simple("${"a".repeat(120)}.jpg" to jpegish)).images.size shouldBe 1
        }

        test("a symlink is refused (Unix mode 0120777 in the external attributes)") {
            rejected(
                TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg", data = jpegish, externalAttributes = 0xA1FFL shl 16))),
            ) shouldBe
                ZipRejectReason.SYMLINK
        }

        test("an encrypted entry (general purpose bit 0) is refused, as is strong encryption (bit 6)") {
            rejected(TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg".toByteArray(), data = jpegish, flags = 1)))) shouldBe
                ZipRejectReason.ENCRYPTED
            rejected(
                TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg".toByteArray(), data = jpegish, flags = 0x40))),
            ) shouldBe
                ZipRejectReason.ENCRYPTED
        }

        test("a nested archive is NESTED_ARCHIVE") {
            for (ext in listOf("zip", "gz", "tar", "7z", "rar", "jar")) {
                rejected(TestZipBuilder.simple("a.$ext" to jpegish)) shouldBe ZipRejectReason.NESTED_ARCHIVE
            }
        }

        test("an unsupported compression method is refused") {
            rejected(
                TestZipBuilder.build(
                    entries = listOf(TestZipEntry(name = "a.jpg".toByteArray(), data = jpegish, method = 12, rawCompressed = jpegish)),
                ),
            ) shouldBe
                ZipRejectReason.UNSUPPORTED_METHOD
        }

        test("a bomb by ratio: 1 MiB of zeros deflates far below 1:100 -> RATIO_EXCEEDED") {
            rejected(TestZipBuilder.simple("a.jpg" to ByteArray(1024 * 1024))) shouldBe ZipRejectReason.RATIO_EXCEEDED
        }

        test("a bomb by total size: 20 entries of 4 MiB of noise -> TOTAL_TOO_LARGE; a single 6 MiB entry -> ENTRY_TOO_LARGE") {
            val random = Random(42)
            val big = random.nextBytes(4 * 1024 * 1024)
            rejected(TestZipBuilder.build(entries = (1..20).map { TestZipEntry(name = "img$it.jpg", data = big, method = 0) })) shouldBe
                ZipRejectReason.TOTAL_TOO_LARGE
            rejected(
                TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg", data = random.nextBytes(6 * 1024 * 1024), method = 0))),
            ) shouldBe
                ZipRejectReason.ENTRY_TOO_LARGE
        }

        test("a lying header: declared small, actually large -> aborted at the first byte over the cap, not inflated to the end") {
            val random = Random(7)
            // 7 MiB of noise stored compressed, but the central directory claims 1000 bytes (ratio fine, size fine)
            val real = ByteArray(7 * 1024 * 1024)
            val compressed = TestZipBuilder.deflateRaw(real)
            val zip =
                TestZipBuilder.build(
                    entries =
                        listOf(
                            TestZipEntry(
                                name = "a.jpg".toByteArray(),
                                data = random.nextBytes(1000),
                                rawCompressed = compressed,
                                declaredCompressed = compressed.size.toLong(),
                                declaredUncompressed = compressed.size.toLong() * 90,
                            ),
                        ),
                )
            // declared uncompressed ~ compressed*90 fits the ratio rule, the real output is far larger than declared or the cap
            val reason = rejected(zip)
            (reason == ZipRejectReason.ENTRY_TOO_LARGE || reason == ZipRejectReason.INCONSISTENT) shouldBe true
        }

        test("local and central view disagree (name, method) -> INCONSISTENT") {
            rejected(
                TestZipBuilder.build(
                    entries = listOf(TestZipEntry(name = "a.jpg".toByteArray(), data = jpegish, localName = "b.jpg".toByteArray())),
                ),
            ) shouldBe
                ZipRejectReason.INCONSISTENT
        }

        test("a wrong CRC-32 is INCONSISTENT") {
            rejected(
                TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg".toByteArray(), data = jpegish, declaredCrc = 1234L))),
            ) shouldBe
                ZipRejectReason.INCONSISTENT
        }

        test("more than 100 entries is refused before anything is read: TOO_MANY_ENTRIES, also when the end record lies about the count") {
            val entries = (1..101).map { TestZipEntry(name = "a$it.jpg", data = jpegish) }
            rejected(TestZipBuilder.build(entries = entries)) shouldBe ZipRejectReason.TOO_MANY_ENTRIES
            rejected(TestZipBuilder.build(entries = entries.take(2), eocdTotal = 200)) shouldBe ZipRejectReason.TOO_MANY_ENTRIES
            ok(TestZipBuilder.build(entries = (1..100).map { TestZipEntry(name = "a$it.jpg", data = jpegish) })).images.size shouldBe 100
        }

        test("an end record that claims more entries than the directory holds is INCONSISTENT") {
            rejected(TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg", data = jpegish)), eocdTotal = 3)) shouldBe
                ZipRejectReason.INCONSISTENT
        }

        test("ZIP64 markers and multi-disk archives are refused") {
            rejected(TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg", data = jpegish)), zip64Marker = true)) shouldBe
                ZipRejectReason.ZIP64_OR_MULTIDISK
            rejected(TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg", data = jpegish)), eocdDisk = 1)) shouldBe
                ZipRejectReason.ZIP64_OR_MULTIDISK
        }

        test("garbage, truncated and empty input are NOT_A_ZIP and never throw") {
            rejected(ByteArray(0)) shouldBe ZipRejectReason.NOT_A_ZIP
            rejected("das ist kein zip".toByteArray()) shouldBe ZipRejectReason.NOT_A_ZIP
            rejected(Random(1).nextBytes(5000)) shouldBe ZipRejectReason.NOT_A_ZIP
            val good = TestZipBuilder.build(entries = listOf(TestZipEntry(name = "a.jpg", data = jpegish)))
            for (cut in listOf(1, 5, 22, good.size / 2, good.size - 1)) {
                (ArticleImportZipReader.read(good.copyOf(cut)) is ZipReadResult.Rejected) shouldBe true
            }
        }

        test("fuzz: random bit flips of a valid ZIP never throw and never return an unvalidated image") {
            val good =
                TestZipBuilder.build(
                    entries =
                        listOf(
                            TestZipEntry(
                                name = "a.jpg",
                                data = jpegish,
                            ),
                            TestZipEntry(
                                name = "b.png",
                                data =
                                    ByteArray(300) {
                                        it.toByte()
                                    },
                            ),
                        ),
                )
            val random = Random(99)
            repeat(400) {
                val copy = good.copyOf()
                repeat(1 + random.nextInt(4)) { copy[random.nextInt(copy.size)] = random.nextInt(256).toByte() }
                val result = ArticleImportZipReader.read(copy)
                if (result is ZipReadResult.Ok) {
                    result.images.forEach { (it.slug == "a" || it.slug == "b") shouldBe true }
                }
            }
        }

        test("duplicate slugs: a.jpg + a.png, a.jpg + a.jpeg and the very same name twice -> none of them is taken, the others are") {
            val result =
                ok(
                    TestZipBuilder.build(
                        entries =
                            listOf(
                                TestZipEntry(name = "a.jpg", data = jpegish),
                                TestZipEntry(name = "a.png", data = jpegish),
                                TestZipEntry(name = "b.jpg", data = jpegish),
                                TestZipEntry(name = "b.jpeg", data = jpegish),
                                TestZipEntry(name = "c.jpg", data = jpegish),
                                TestZipEntry(name = "c.jpg", data = jpegish),
                                TestZipEntry(name = "d.jpg", data = jpegish),
                            ),
                    ),
                )
            result.duplicateSlugs shouldBe setOf("a", "b", "c")
            result.images.map { it.slug } shouldBe listOf("d")
        }

        test(
            "overlapping entries: two central entries of the same name pointing at the same local data are refused (not merely as a name mismatch)",
        ) {
            val two =
                TestZipBuilder.build(
                    entries = listOf(TestZipEntry(name = "a.jpg", data = jpegish), TestZipEntry(name = "a.jpg", data = jpegish)),
                )
            // the unpatched archive is fine on its own (two entries of the same name = a duplicate slug, nothing is taken)
            ok(two).duplicateSlugs shouldBe setOf("a")
            val cdStart = two.size - 22 - 2 * (46 + "a.jpg".length)
            val secondHeader = cdStart + 46 + "a.jpg".length
            val patched = two.copyOf()
            for (i in 0 until 4) patched[secondHeader + 42 + i] = 0
            rejected(patched) shouldBe ZipRejectReason.INCONSISTENT
        }

        test("the reader and the parser never use the file system: no File, Files or path API in the ZIP source files") {
            val root = java.io.File("src/main/kotlin").let { if (it.exists()) it else java.io.File("lapis-server/src/main/kotlin") }
            for (name in listOf("ArticleImportZip.kt", "ArticleImportImages.kt")) {
                val text =
                    network.lapis.cloud.server.db.SourceScan.blank(
                        java.io.File(root, "network/lapis/cloud/server/articles/$name").readText(),
                    )
                for (forbidden in listOf(
                    "java.io.File",
                    "File(",
                    "Files.",
                    "java.nio.file",
                    "Paths.",
                    "Path(",
                    "createTemp",
                    "FileOutputStream",
                    "ZipInputStream",
                    "ZipFile",
                )) {
                    (text.contains(forbidden)) shouldBe false
                }
            }
        }
    })
